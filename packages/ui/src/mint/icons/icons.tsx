import type { ReactNode } from "react";

export type IconProps = {
  /** The rendered size in px; the grid stays 24. */
  readonly size?: number;
  readonly className?: string;
};

type FilledProps = IconProps & {
  /** The solid twin, for the current page. */
  readonly filled?: boolean;
};

function Glyph({
  size = 20,
  className,
  children,
}: IconProps & { readonly children: ReactNode }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

